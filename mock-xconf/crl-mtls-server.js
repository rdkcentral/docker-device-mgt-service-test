/**
 * CRL mTLS Server (L3)
 *
 * Listens on port 50061 with mutual TLS enforced.  The server certificate is
 * signed by Test-CRL-ICA; client certificates must be signed by Test-CRL-ICA
 * (CRL tests) or carry a valid cross-signed bridge to Test-XS-NewRoot (xsign
 * tests).  The active CRL is reloaded live via setSecureContext() so no restart
 * is required after a revocation event.
 *
 * Endpoints:
 *   GET /health  →  {"status":"ok"}  HTTP 200  (used by test driver)
 *
 * The HTTP control server on port 50062 is started by requiring crl-control.js.
 *
 * Security notes:
 *   - Private key material (contents/passphrases) is never written to logs.
 *   - requestCert + rejectUnauthorized ensure clients without a valid cert are
 *     rejected at the TLS layer, not the application layer.
 */

'use strict';

const https = require('node:https');
const fs    = require('node:fs');

// ─── Configuration ────────────────────────────────────────────────────────────

const PORT = 50061;

// Server-side TLS material (created by certs.sh CRL-L3 block)
const SERVER_KEY  = '/etc/xconf/certs/crl/crl-server.key';
const SERVER_CERT = '/etc/xconf/certs/crl/crl-server.pem';

// CA trust for client-certificate verification
// Always include both CRL root and XS-NewRoot so that:
//   – crl-client.p12  (chain: leaf → ICA → CRL-Root)      validates via CRL_ROOT
//   – client-xsign.p12 (chain includes bridge → XS-NewRoot) validates via NEWROOT
const CRL_ROOT = '/etc/xconf/certs/crl/Test-CRL-Root.pem';
const CRL_ICA  = '/etc/xconf/certs/crl/Test-CRL-ICA.pem';
const NEWROOT  = '/mnt/L2_CONTAINER_SHARED_VOLUME/shared_certs/xs-client/NewRoot.pem';

// CRL file updated in-place by crl-control.js after revocation events
const CRL_FILE      = '/etc/xconf/certs/crl/Test-CRL-ICA.crl.pem';
// Root CA CRL: static empty CRL required by OpenSSL 3 CRL_CHECK_ALL.
// No certs are ever revoked at root level; this file never changes.
const ROOT_CRL_FILE = '/etc/xconf/certs/crl/Test-CRL-Root.crl.pem';

// XS PKI CRL directory — empty CRLs generated by certs.sh for each XS CA.
// Required because OpenSSL 3 CRL_CHECK_ALL verifies every cert in the chain.
const XS_CRL_DIR = '/mnt/L2_CONTAINER_SHARED_VOLUME/shared_certs/xs-client';

// ─── Startup diagnostics ──────────────────────────────────────────────────────

console.log('[crl-mtls-server] =====================================');
console.log('[crl-mtls-server] CRL mTLS Server starting');
console.log('[crl-mtls-server] =====================================');
console.log(`[crl-mtls-server] Node.js ${process.version}  PID ${process.pid}`);
console.log(`[crl-mtls-server] Target port: ${PORT}`);

for (const f of [SERVER_KEY, SERVER_CERT, CRL_ROOT, CRL_ICA, CRL_FILE, ROOT_CRL_FILE]) {
  const ok = fs.existsSync(f);
  console.log(`[crl-mtls-server]   ${ok ? '✓' : '✗'} ${f}`);
  if (!ok) {
    console.error(`[crl-mtls-server] FATAL: required file missing: ${f}`);
    process.exit(1);
  }
}
if (fs.existsSync(NEWROOT)) {
  console.log(`[crl-mtls-server]   ✓ ${NEWROOT}  (xsign mode enabled)`);
} else {
  console.log(`[crl-mtls-server]   – ${NEWROOT}  (not present; xsign tests will fail)`);
}

// ─── TLS options builder ──────────────────────────────────────────────────────

/**
 * Build the current TLS options object by reading cert/key/CRL files from
 * disk.  Called once at start-up and again by crl-control.js via
 * setSecureContext() after every revocation operation.
 *
 * @returns {object}  Options suitable for https.createServer() or
 *                    server.setSecureContext().
 */
function buildTlsOptions() {
  const caChunks = [
    fs.readFileSync(CRL_ROOT),
    fs.readFileSync(CRL_ICA),
  ];
  if (fs.existsSync(NEWROOT)) {
    caChunks.push(fs.readFileSync(NEWROOT));
  }

  // CRL pool: always include the CRL PKI CRLs; add XS PKI CRLs if present.
  const crlChunks = [fs.readFileSync(CRL_FILE), fs.readFileSync(ROOT_CRL_FILE)];
  if (fs.existsSync(XS_CRL_DIR)) {
    for (const f of fs.readdirSync(XS_CRL_DIR)) {
      if (f.endsWith('.crl.pem')) {
        crlChunks.push(fs.readFileSync(`${XS_CRL_DIR}/${f}`));
      }
    }
  }

  // Send the full server cert chain (leaf + ICA) so clients can verify
  // the server without needing Test-CRL-ICA pre-installed.
  const certChain = Buffer.concat([
    fs.readFileSync(SERVER_CERT),
    fs.readFileSync(CRL_ICA),
  ]);

  return {
    key:               fs.readFileSync(SERVER_KEY),
    cert:              certChain,
    ca:                caChunks,
    crl:               crlChunks,
    requestCert:       true,
    rejectUnauthorized: true,
  };
}

// ─── HTTPS server ─────────────────────────────────────────────────────────────

const server = https.createServer(buildTlsOptions(), (req, res) => {
  if (req.method === 'GET' && req.url === '/health') {
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ status: 'ok' }));
    return;
  }
  res.writeHead(404);
  res.end();
});

server.listen(PORT, () => {
  console.log(`[crl-mtls-server] Listening on port ${PORT}  (mTLS + CRL enforced)`);
});

server.on('tlsClientError', (err) => {
  console.error(`[crl-mtls-server] tlsClientError: ${err.code} ${err.message}`);
});

// ─── Exports for crl-control.js ───────────────────────────────────────────────

module.exports = { server, buildTlsOptions };

// ─── Start HTTP control server (port 50062) ───────────────────────────────────
// Loaded here so both servers share a single Node.js process, enabling live
// setSecureContext() calls without IPC.
require('./crl-control');
